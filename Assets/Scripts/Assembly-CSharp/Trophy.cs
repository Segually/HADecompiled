public class Trophy
{
	public string trophy_name;

	public string trophy_reason;

	public string trophy_paint;

	public string trophy_from;

	public string trophy_rand_id;

	public string trophy_date;

	public Trophy(string trophy_name, string trophy_reason, string trophy_paint, string trophy_from, string trophy_rand_id, string trophy_date)
	{
		this.trophy_name = trophy_name;
		this.trophy_reason = trophy_reason;
		this.trophy_paint = trophy_paint;
		this.trophy_from = trophy_from;
		this.trophy_rand_id = trophy_rand_id;
		this.trophy_date = trophy_date;
	}
}
